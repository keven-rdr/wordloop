import type { ReactNode, SVGProps } from 'react';

type IconProps = Readonly<SVGProps<SVGSVGElement>>;

function Icon({ children, ...rest }: IconProps & Readonly<{ children: ReactNode }>) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2.5}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      {...rest}
    >
      {children}
    </svg>
  );
}

